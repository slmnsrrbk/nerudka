# Собирает competitors/AUDIENCE.md из competitors/audience.json (см. scripts/audience-data.py).
import json
d = json.load(open('competitors/audience.json'))
FIGMA = 'https://www.figma.com/design/juFVw7SDIxDw0StkPZCTHH/?node-id=%s'
PAGE = '136-2'  # страница «ЦА и блок-схемы»
SRC, Q = d['sources'], {q['id']: q for q in d['questions']}
SEG = {s['id']: s for s in d['segments']}


def link(k):
    s = SRC[k]
    url = s['url'] if s['url'].startswith('http') else s['url']
    mark = '' if s['kind'] == 'audit' else '*'
    return f"[{k}{mark}]({url})"


def srcs(ks):
    return ' '.join(link(k) for k in ks)


L = ['# ЦА: вопросы клиентов и блок-схемы вариантов П1–П6', '',
     f'Тот же материал в Figma: [страница «ЦА и блок-схемы»]({FIGMA % PAGE}). Варианты главной: [«Прототипы главной · по анализу»]({FIGMA % "117-2"}).', '',
     '**Содержание:** [Как собрано](#как-собрано) · [Сегменты](#сегменты-и-что-о-них-известно) · [20 вопросов](#20-вопросов-клиента) · [Покрытие](#покрытие-вопросов-по-вариантам) · [Блок-схемы](#блок-схемы-вариантов) · [Гайд для интервью](#гайд-для-настоящих-интервью) · [Источники](#источники)', '',
     '## Как собрано', '',
     '- **Настоящих интервью здесь нет.** Людей и цитаты не придумывали. Раздел «Гайд для настоящих интервью» — что спросить у 5–7 клиентов каждого сегмента; ответы добавим в эту таблицу.',
     '- **Голос клиента** — только проверяемое: вопросы из блоков FAQ на главных 20 доступных конкурентов (сняты нашим скриптом, `competitors/audit/`), жалобы из отзывов, статьи о выборе поставщика.',
     '- FAQ конкурентов — это вопросы, которые заводы **сами** вынесли на сайт. Сигнал косвенный, но повторяющийся у разных компаний.',
     '- Ссылки со звёздочкой (`S12*`) — страница закрыта для нашей рабочей среды, факт взят из поисковой выдачи. Перед показом клиенту открыть и перепроверить.',
     '- Сегменты — гипотеза: ksg-beton прямо делит клиентов на частных заказчиков, подрядчиков и организации ' + link('S02') + ', обзор рынка говорит, что основной спрос даёт B2B ' + link('S20') + '. Долю сегментов у нашего клиента нужно взять из его заявок и CRM.',
     '- Какой блок на какой вопрос отвечает — разобрано по тексту самих макетов П1–П6 в Figma.', '']

L += ['## Сегменты и что о них известно', '']
for s in d['segments']:
    L += [f"### {s['id']} · {s['name']}", '', s['who'] + ' Основание сегмента: ' + srcs(s['basis']), '', '**Что говорят и спрашивают:**', '']
    L += [f"- {v['text']} {srcs(v['src'])}" for v in s['voice']]
    L += ['', '**Вопросы сегмента:** ' + ', '.join(f"{q} {Q[q]['text']}" for q in s['questions']), '']

L += ['## 20 вопросов клиента', '', '| # | Вопрос | Сегменты | Откуда |', '|---|---|---|---|']
for q in d['questions']:
    L.append(f"| {q['id']} | {q['text']} | {', '.join(q['segments'])} | {srcs(q['src'])} |")

vs = d['variants']
L += ['', '## Покрытие вопросов по вариантам', '', 'Сколько вопросов сегмента закрывает главная (ответ есть прямо в блоке).', '',
      '| Сегмент | ' + ' | '.join(f"{v['id']} {v['name']}" for v in vs) + ' |', '|---|' + '---|' * len(vs)]
for s in d['segments']:
    L.append(f"| {s['id']} {s['name']} | " + ' | '.join(f"{v['coverage'][s['id']][0]}/{v['coverage'][s['id']][1]}" for v in vs) + ' |')
L.append('| **Всего из 20** | ' + ' | '.join(f"**{len(v['covered'])}**" for v in vs) + ' |')
nobody = [q for q in Q if all(q in v['missing'] for v in vs)]
L += ['', 'Ни один вариант не отвечает на: ' + '; '.join(f"**{q}** {Q[q]['text']}" for q in nobody) + '.',
      'Частые пробелы — зима (Q12), остаток и дозаказ (Q19), самовывоз (Q20) — закрываются данными, которые уже есть в прототипе: зима — `services.json` (прогрев от 350 ₽/м³, до −25 °C), самовывоз — `faq.json` («в прайсе цена смеси за куб на условиях самовывоза»), запас объёма — `posts.json` (5 %). Условия дозаказа — [заглушка].',
      'Расхождение в прототипе: калькулятор в П5 считает запас 3 %, а статья в `posts.json` — 5 %. Нужно выбрать одно.', '']
L += ['## Блок-схемы вариантов', '']
for v in vs:
    L += [f"### {v['id']} · {v['name']}", '', f"[Открыть макет в Figma]({FIGMA % v['node'].replace(':', '-')})", '', '```mermaid', 'flowchart TD']
    for i, b in enumerate(v['blocks']):
        qs = ' · '.join(b['q'])
        L.append(f"  B{i}[\"{b['n']} {b['name']}<br/><small>{qs}</small>\"]")
        if i:
            L.append(f"  B{i-1} --> B{i}")
    L.append(f"  G[\"Без ответа: {', '.join(v['missing'])}\"]:::gap")
    L.append(f"  B{len(v['blocks'])-1} -.-> G")
    L += ['  classDef gap fill:#fde2e1,stroke:#c0392b', '```', '',
          '| Блок | Отвечает на вопросы |', '|---|---|']
    L += [f"| {b['n']} {b['name']} | " + '<br>'.join(f"{q} {Q[q]['text']}" for q in b['q']) + ' |' for b in v['blocks']]
    L += ['', '**Без ответа:** ' + '; '.join(f"{q} {Q[q]['text']}" for q in v['missing']), '',
          '**Чем закрыть (только факты из данных прототипа):**', '']
    L += [f"- {f['text']} → {', '.join(f['q'])}" for f in v['fixes']]
    L += ['']

L += ['## Гайд для настоящих интервью', '',
      'По 5–7 человек на сегмент, 20–30 минут, по телефону. Кого звать: клиенты завода за последние 3 месяца (из CRM) и те, кто оставил заявку, но не купил. Записываем дословно, потом раскладываем ответы по вопросам Q01–Q20 и дописываем новые.', '']
for s in d['segments']:
    L += [f"**{s['id']} · {s['name']}**", ''] + [f"{i+1}. {g}" for i, g in enumerate(s['guide'])] + ['']
L += ['В конце каждого интервью показать 2–3 варианта главной (П1–П6) и спросить: «Где вы быстрее нашли бы ответ на свой вопрос?»', '']

L += ['## Источники', '', '| # | Источник | Как проверено |', '|---|---|---|']
for k, s in SRC.items():
    how = 'снято нашим скриптом с главной' if s['kind'] == 'audit' else 'по поисковой выдаче, страница закрыта для среды'
    L.append(f"| {k} | [{s['title']}]({s['url']}) | {how} |")
L.append('')
open('competitors/AUDIENCE.md', 'w').write('\n'.join(L))
print(len(L), 'строк')
