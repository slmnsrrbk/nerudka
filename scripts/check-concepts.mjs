// Проверка страницы концептов /concepts/: интерактив каждого концепта и адаптив.
import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
p.on('pageerror', (e) => errors.push(String(e)));
await p.goto('http://localhost:4321/concepts/', { waitUntil: 'networkidle' });
const res = [];
res.push(['страница открылась', (await p.title()).includes('концепта')]);
res.push(['борт отгрузок заполнен', (await p.locator('#c1-rows tr').count()) === 7]);
res.push(['тепловая карта построена', (await p.locator('#c1-heat .cell').count()) === 84]);
await p.locator('.c1 .slot[data-slot="15:30"]').click();
res.push(['слот выбирается', (await p.textContent('#c1-btn')).includes('15:30')]);
await p.locator('#c1-heat .cell').nth(20).hover();
await p.waitForTimeout(150);
res.push(['подсказка по клетке появляется', (await p.textContent('#c1-tip')).length > 30]);
const t0 = await p.textContent('#c2-total');
await p.selectOption('#c2-grade', { index: 2 });
await p.fill('#c2-vol', '60');
await p.waitForTimeout(200);
const t1 = await p.textContent('#c2-total');
res.push([`чек пересчитался ${t0.trim()} -> ${t1.trim()}`, t0 !== t1]);
res.push(['скидка за объём применилась', (await p.textContent('#c2-v4')).includes('минус')]);
await p.locator('.c3 .zone[data-z="otmostka"]').hover();
await p.waitForTimeout(200);
res.push(['разрез переключает конструкцию', (await p.textContent('#c3-n')).includes('Отмостка')]);
res.push(['объём пересчитался под конструкцию', (await p.textContent('#c3-vol')) !== '25,20 м³']);
res.push(['прайс построен', (await p.locator('#c4-grid .cellp').count()) === 12]);
const p0 = (await p.textContent('#c4-grid .cellp i')).trim();
await p.selectOption('#c4-zone', '900');
await p.waitForTimeout(200);
const p1 = (await p.textContent('#c4-grid .cellp i')).trim();
res.push([`зона пересчитала прайс ${p0} -> ${p1}`, p0 !== p1]);
const ovf = await p.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
res.push([`нет горизонтального скролла на 1440 (${ovf})`, ovf <= 0]);
const m = await b.newPage({ viewport: { width: 375, height: 900 } });
await m.goto('http://localhost:4321/concepts/', { waitUntil: 'networkidle' });
const ovfm = await m.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
res.push([`нет горизонтального скролла на 375 (${ovfm})`, ovfm <= 0]);
for (const [n, ok] of res) console.log(`${ok ? 'OK  ' : 'СБОЙ'} ${n}`);
console.log(errors.length ? 'Ошибки JS: ' + errors.join('; ') : 'Ошибок JS нет');
await b.close();
process.exit(res.every(([, ok]) => ok) && errors.length === 0 ? 0 : 1);
