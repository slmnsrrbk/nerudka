def link(k):
    s = SRC[k]
    url = s['url'] if s['url'].startswith('http') else s['url']
    mark = '' if s['kind'] == 'audit' else '*'
    return f"[{k}{mark}]({url})"


def srcs(ks):
    return ' '.join(link(k) for k in ks)


