# Собирает competitors/ANALYSIS.md из competitors/analysis.json.
import json
d = json.load(open('competitors/analysis.json'))
import glob, os
FIGMA = 'https://www.figma.com/design/juFVw7SDIxDw0StkPZCTHH/?node-id=111-2'
L = ['# Анализ главных страниц 14 конкурентов', '',
     f'Тот же анализ в Figma с полными скриншотами: [страница «Анализ конкурентов»]({FIGMA}).', '',
     '**Содержание:** [Коротко](#коротко) · [Сравнительная таблица](#сравнительная-таблица) · [Что хорошо и что взять](#что-хорошо-и-что-взять) · [Структура каждого сайта](#структура-каждого-сайта) · [Матрица блоков](#матрица-какие-блоки-есть-на-главной) · [Общий вывод](#общий-вывод)', '',
     f"Снято {d['date']} скриптом `scripts/competitor-audit.mjs`, сырые данные и скриншоты — в `competitors/audit/`. Цифры и формулировки — как на самих сайтах.", '',
     'Семейства похожих сайтов: **A** — сеть GMR (01, 02, 08: одинаковый контент), **B** — один шаблон 1С-Битрикс (04, 06), **C** — одна студия (05, 07, 11).', '']
S = d['summary']
L += ['## Коротко', '',
      '- Работают 13 сайтов из 14: betonmks.ru заблокирован хостингом.',
      '- Три группы сайтов сделаны по одному шаблону и узнаются сразу: сеть GMR (01, 02, 08), шаблон 1С-Битрикс (04, 06), одна студия (05, 07, 11).',
      '- Сильнее всех по продажам — БСТ (12): сегменты «Что вы строите?», проверка поставщика, честные блоки про цену.',
      '- Лучший ход против перекупщиков — у МосАвтоБетона (02): ИНН «проверьте сами», «не меняем ООО», «Нашли дешевле? Снизим цену».',
      '- Общая ошибка — SEO-простыни посреди продающих блоков: у GMR, МосАвтоБетона и ГСТ главные по 19–20 тыс. px.', '']
L += ['## Сравнительная таблица', '', '| Сайт | Первый экран | Формы и лид-магниты | Доверие | Контакты |', '|---|---|---|---|---|']
for s in d['sites']:
    L.append(f"| **{s['id']} · {s['name']}**<br>[{s['url'].replace('https://', '').rstrip('/')}]({s['url']})<br>{s['cms']} | {s['hero']} | {s['leads']} | {s['trust']} | {s['contacts']} |")
L += ['', '## Что хорошо и что взять', '', '| Сайт | Что хорошо для продаж | Слабые места | Что можно взять |', '|---|---|---|---|']
br = lambda a: '<br>'.join('• ' + x for x in a) if a else '—'
for s in d['sites']:
    L.append(f"| **{s['id']} · {s['name']}** | {br(s['good'])} | {br(s['bad'])} | {br(s['take'])} |")
L += ['', '## Структура каждого сайта', '']
for s in d['sites']:
    fam = f", семейство {s['family']}" if s['family'] != '—' else ''
    L += [f"### {s['id']} · {s['name']} — [{s['url'].replace('https://', '').rstrip('/')}]({s['url']})", '',
          f"{s['cms']}, высота главной ≈ {s['height']:,} px{fam}".replace(',', ' '), '', '**Структура главной сверху вниз:**', '']
    L += [f"{i + 1}. {x}" for i, x in enumerate(s['structure'])]
    for t, k in [('Что хорошо для продаж', 'good'), ('Слабые места', 'bad'), ('Что можно взять', 'take')]:
        if s[k]:
            L += ['', f'**{t}:**', ''] + ['- ' + x for x in s[k]]
    shots = sorted(glob.glob(f"competitors/audit/{s['id']}-*-p*.jpg"))
    if shots:
        L += ['', '**Скриншот главной:** ' + ' · '.join(f"[часть {i + 1}](audit/{os.path.basename(f)})" for i, f in enumerate(shots))]
    L += ['']
ids = [s['id'] for s in d['sites']]
L += ['## Матрица: какие блоки есть на главной', '', '| Блок | ' + ' | '.join(ids) + ' | Всего |', '|---|' + '---|' * len(ids) + '---|']
for name, m in d['blocks']:
    L.append(f"| {name} | " + ' | '.join('●' if i in m else '' for i in ids) + f" | {len(m)} |")
L += ['', '## Общий вывод', '', '### База рынка — должно быть у нас тоже', ''] + ['- ' + x for x in S['base']]
L += ['', '### Идеи, которые можно взять', '', '| № | Идея | Источник |', '|---|---|---|'] + [f"| {a} | {b} | {c} |" for a, b, c in S['ideas']]
L += ['', '### Чего избегать', ''] + ['- ' + x for x in S['avoid']]
L += ['', '## Как собраны данные', '', '- Главные страницы открыты 25.09.2026 браузером Chromium с раннера GitHub Actions, ширина 1440 px.', '- Скрипт `scripts/competitor-audit.mjs` выгрузил блоки по заголовкам, формы, цены, мессенджеры и виджеты в `competitors/audit/*.json`, скриншоты — там же.', '- Структура и оценки проверены по скриншотам вручную; этот файл собирается из `competitors/analysis.json` скриптом `scripts/analysis-md.py`.']
open('competitors/ANALYSIS.md', 'w').write('\n'.join(L) + '\n')
